#!/usr/bin/env node
// tools/ai/openai-copy.js - "use OpenAI for CW": two alternative phrasings per copy.json key (+ exceptions E1-E23) and a
// proposal for the candidate key `select.encouragement`, via the OpenAI Responses API with strict JSON-schema output.
// Writes reports/ai/copy-proposals.json and reports/ai/copy-proposals.md. PROPOSALS ONLY: packages/contracts/copy.json is
// never touched (content review is open decision OD-11).
//
//   node tools/ai/openai-copy.js --dry-run              print the developer prompt + every batch request, write reports/ai/dry-run/*.json
//   node tools/ai/openai-copy.js                        real run (needs OPENAI_API_KEY in .env)
//   options: --model <id> (default env OPENAI_TEXT_MODEL / gpt-5.1)  --batch-size <n> (default 24)  --only <key prefix, repeatable>
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadEnv, requireKey, redact, ROOT } from './env.js';
import { REPORTS_AI, log, warn, parseArgs, postJson, readJson, shapeDryRun, writeDryRun, writeJson, writeText } from './lib/common.js';
import { OPENAI_RESPONSES_URL, buildResponsesRequest, openaiHeaders, parseStructured, usageOf } from './lib/openai.js';
import { BATCH_SCHEMA, CANDIDATE_KEY, CANDIDATE_SCHEMA, HARD_RULES, buildBatchUserPrompt, buildCandidateUserPrompt, buildCopySystemPrompt, catalogueItems, chunk, lintText, loadToneSources, reviewBatch } from './lib/copy-rules.js';
import { validateSchema } from './lib/schema.js';

export const COPY_PATH = join(ROOT, 'packages', 'contracts', 'copy.json');
export const OUT_JSON = join(REPORTS_AI, 'copy-proposals.json');
export const OUT_MD = join(REPORTS_AI, 'copy-proposals.md');
const HEADER = 'PROPOSALS ONLY - generated by tools/ai/openai-copy.js. Nothing here is adopted automatically; packages/contracts/copy.json is unchanged. Content review is open decision OD-11 (content owner).';

/** Pure plan: system prompt + one request per batch + the candidate request. */
export function planRun({ copy, tone, model, batchSize = 24, only = null }) {
  let items = catalogueItems(copy);
  if (only) { const prefixes = [].concat(only); items = items.filter((i) => prefixes.some((p) => i.key.startsWith(p))); }
  if (!items.length) throw new Error('no copy keys match --only');
  const system = buildCopySystemPrompt(tone);
  const batches = chunk(items, batchSize);
  const requests = batches.map((b, i) => ({ name: `batch-${String(i + 1).padStart(2, '0')}`, items: b, body: buildResponsesRequest({ model, system, user: buildBatchUserPrompt(b, i, batches.length), schemaName: 'copy_proposals', schema: BATCH_SCHEMA, maxOutputTokens: 12000 }) }));
  requests.push({ name: 'candidate-select-encouragement', items: [], candidate: true, body: buildResponsesRequest({ model, system, user: buildCandidateUserPrompt(), schemaName: 'copy_candidate', schema: CANDIDATE_SCHEMA, maxOutputTokens: 2000 }) });
  return { system, items, requests };
}

export function renderMarkdown(report) {
  const L = [`# Copy proposals (CW) - ${report.model}`, '', `> ${HEADER}`, '', `Generated ${report.createdAt}. ${report.summary.keys} keys, ${report.summary.alternatives} alternatives (${report.summary.lintRejected} rejected by lint), ${report.summary.requests} request(s).`, '',
    '## Hard rules applied', ...HARD_RULES.map((r) => `- ${r}`), '',
    `## Candidate key \`${CANDIDATE_KEY}\``, ''];
  if (report.candidate) {
    L.push(`Purpose: ${report.candidate.purpose}`, '', `Placement note: ${report.candidate.placementNote}`, '');
    for (const o of report.candidate.options) L.push(`- ${o.lint === 'ok' ? '' : '~~'}${o.text}${o.lint === 'ok' ? '' : '~~ (rejected: ' + o.problems.join('; ') + ')'} - ${o.rationale}`);
  } else L.push('_not generated in this run_');
  L.push('', '## Alternatives per existing key', '', 'Strike-through = rejected by lint (kept for transparency, never to be adopted).', '');
  for (const p of report.proposals) {
    L.push(`### \`${p.key}\``, `Current: ${p.current}${p.context ? `  \n_${p.context}_` : ''}`);
    for (const a of p.alternatives) L.push(`- ${a.lint === 'ok' ? a.text : `~~${a.text}~~ (rejected: ${a.problems.join('; ')})`}  \n  _${a.rationale}_`);
    L.push('');
  }
  if (report.missing.length) L.push('## Keys without a proposal', ...report.missing.map((k) => `- ${k}`), '');
  if (report.errors.length) L.push('## Request errors', ...report.errors.map((e) => `- ${e}`), '');
  return L.join('\n');
}

export async function main(argv = process.argv.slice(2)) {
  const args = parseArgs(argv, { booleans: ['dry-run', 'help'] });
  if (args.help) { log(readFileSync(fileURLToPath(import.meta.url), 'utf8').split('\n').slice(1, 10).join('\n')); return 0; }
  const env = loadEnv();
  const model = args.model || env.OPENAI_TEXT_MODEL;
  const copy = readJson(COPY_PATH);
  const tone = loadToneSources();
  const plan = planRun({ copy, tone, model, batchSize: Number(args['batch-size'] || 24), only: args.only || null });
  const dryRun = !!args['dry-run'];

  if (dryRun) {
    log(`DRY RUN - nothing is sent. ${plan.items.length} keys in ${plan.requests.length} request(s) to ${OPENAI_RESPONSES_URL} (model ${model}).`);
    log('\n### developer (system) prompt\n' + plan.system);
    for (const r of plan.requests) {
      const rec = shapeDryRun({ tool: 'openai-copy', name: r.name, url: OPENAI_RESPONSES_URL, headers: openaiHeaders('<OPENAI_API_KEY>'), body: r.body, outputs: [OUT_JSON, OUT_MD], notes: [HEADER] });
      const file = writeDryRun(rec);
      log(`\n### ${r.name} -> ${file}\n` + r.body.input[1].content[0].text);
    }
    log(`\nKey status: OPENAI_API_KEY ${env.OPENAI_API_KEY ? 'present' : 'EMPTY (fill .env before a real run)'}`);
    return 0;
  }

  const key = requireKey(env, 'OPENAI_API_KEY');
  const report = { note: HEADER, tool: 'tools/ai/openai-copy.js', model, createdAt: new Date().toISOString(), summary: {}, usage: [], candidate: null, proposals: [], rejectedResponses: [], missing: [], errors: [] };
  for (const r of plan.requests) {
    log(`-> ${r.name} (${r.items.length || 'candidate'} ${r.candidate ? '' : 'keys'})`);
    try {
      const res = await postJson(OPENAI_RESPONSES_URL, { headers: openaiHeaders(key), body: r.body, timeoutMs: 240000 });
      report.usage.push({ request: r.name, ...usageOf(res) });
      const data = parseStructured(res);
      const errors = validateSchema(r.candidate ? CANDIDATE_SCHEMA : BATCH_SCHEMA, data);
      if (errors.length) throw new Error(`response failed schema validation: ${errors.slice(0, 5).join('; ')}`);
      if (r.candidate) {
        report.candidate = { ...data, key: CANDIDATE_KEY, options: data.options.map((o) => { const hits = lintText(o.text); return { ...o, lint: hits.length ? 'rejected' : 'ok', problems: hits.length ? [`forbidden wording: ${hits.join(', ')}`] : [] }; }) };
      } else {
        const rev = reviewBatch(r.items, data);
        report.proposals.push(...rev.accepted);
        report.rejectedResponses.push(...rev.rejected);
        report.missing.push(...rev.missing);
      }
    } catch (e) { const msg = `${r.name}: ${redact(e.message)}`; report.errors.push(msg); warn(`FAILED ${msg}`); if (!r.candidate) report.missing.push(...r.items.map((i) => i.key)); }
  }
  const alts = report.proposals.flatMap((p) => p.alternatives);
  report.summary = { keys: report.proposals.length, alternatives: alts.length, lintRejected: alts.filter((a) => a.lint !== 'ok').length, requests: plan.requests.length, missing: report.missing.length, errors: report.errors.length };
  writeJson(OUT_JSON, report);
  writeText(OUT_MD, renderMarkdown(report));
  log(`Wrote ${OUT_JSON} and ${OUT_MD}: ${report.summary.keys} keys, ${report.summary.alternatives} alternatives, ${report.summary.lintRejected} lint-rejected, ${report.summary.errors} error(s). copy.json untouched.`);
  return report.errors.length ? 1 : 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().then((code) => process.exit(code)).catch((e) => { warn(`error: ${redact(e.message)}`); process.exit(1); });
}
