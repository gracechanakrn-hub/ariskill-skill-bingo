#!/usr/bin/env node
// tools/ai/openai-uxui.js - "use OpenAI for UX/UI template": one structured proposal per screen (employee join / select /
// board / playing / result / soul; stage; public; admin) via the OpenAI Responses API (strict JSON schema).
// Writes reports/ai/uxui-template.json and reports/ai/uxui-template.md. PROPOSAL ONLY - apps/ are never modified.
//
//   node tools/ai/openai-uxui.js --dry-run              print the developer prompt + one request per screen, write reports/ai/dry-run/*.json
//   node tools/ai/openai-uxui.js --only stage --only admin
//   options: --model <id> (default env OPENAI_TEXT_MODEL / gpt-5.1)  --list
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadEnv, requireKey, redact } from './env.js';
import { REPORTS_AI, log, warn, parseArgs, postJson, shapeDryRun, writeDryRun, writeJson, writeText } from './lib/common.js';
import { OPENAI_RESPONSES_URL, buildResponsesRequest, openaiHeaders, parseStructured, usageOf } from './lib/openai.js';
import { SCREENS, SCREEN_SCHEMA, allowedTokenNames, buildScreenUserPrompt, buildUxSystemPrompt, loadUxSources, reviewScreen } from './lib/uxui-rules.js';
import { validateSchema } from './lib/schema.js';

export const OUT_JSON = join(REPORTS_AI, 'uxui-template.json');
export const OUT_MD = join(REPORTS_AI, 'uxui-template.md');
const HEADER = 'PROPOSAL ONLY - generated by tools/ai/openai-uxui.js for the design owner. No app, token or copy file is changed by this tool. Token names are constrained to design-tokens 1.1.0 plus the --sticker-* names of docs/art/sticker-art-direction.md (1.2.0 pending, D-25 provisional).';

export function planRun({ src, model, only = null }) {
  const screens = SCREENS.filter((s) => !only || [].concat(only).includes(s.id));
  if (!screens.length) throw new Error('no screen matches --only; use --list');
  const system = buildUxSystemPrompt(src);
  return { system, requests: screens.map((s) => ({ name: s.id, screen: s, body: buildResponsesRequest({ model, system, user: buildScreenUserPrompt(s), schemaName: 'uxui_screen_template', schema: SCREEN_SCHEMA, maxOutputTokens: 9000 }) })) };
}

export function renderMarkdown(report) {
  const L = [`# UX/UI template proposals - ${report.model}`, '', `> ${HEADER}`, '', `Generated ${report.createdAt}. ${report.screens.length} screen(s).`, ''];
  for (const s of report.screens) {
    L.push(`## ${s.title}`, '', s.proposal.summary, '');
    if (s.review.unknownTokens.length) L.push(`**Unknown token names flagged (not in the allowed list):** ${s.review.unknownTokens.map((t) => `\`${t}\``).join(', ')}`, '');
    L.push('### Layout regions', ...s.proposal.layoutRegions.map((r) => `- **${r.id}** (${r.role}, ${r.placement}): ${r.contains.join(', ')}`), '');
    L.push('### Components');
    for (const c of s.proposal.components) L.push(`- **${c.name}** in ${c.region} - ${c.variant}; states: ${c.states.join(', ') || '-'}; tokens: ${c.tokens.map((t) => `\`${t}\``).join(', ') || '-'}; copy: ${c.copyKeys.map((k) => `\`${k}\``).join(', ') || '-'}${c.notes ? `  \n  _${c.notes}_` : ''}`);
    L.push('', '### Token usage', ...s.proposal.tokenUsage.map((t) => `- \`${t.token}\`: ${t.use}`), '');
    L.push('### Motion cues', ...s.proposal.motion.map((m) => `- ${m.trigger}: ${m.cue} (\`${m.durationToken}\`; reduced motion: ${m.reducedMotion})`), '');
    L.push('### Accessibility notes', ...s.proposal.accessibility.map((a) => `- ${a}`), '');
    L.push('### Sticker art-direction notes', ...s.proposal.stickerNotes.map((a) => `- ${a}`), '');
    L.push('### Open questions for the design owner', ...s.proposal.openQuestions.map((a) => `- ${a}`), '');
  }
  if (report.errors.length) L.push('## Request errors', ...report.errors.map((e) => `- ${e}`), '');
  return L.join('\n');
}

export async function main(argv = process.argv.slice(2)) {
  const args = parseArgs(argv, { booleans: ['dry-run', 'list', 'help'] });
  if (args.help) { log(readFileSync(fileURLToPath(import.meta.url), 'utf8').split('\n').slice(1, 9).join('\n')); return 0; }
  if (args.list) { for (const s of SCREENS) log(`${s.id.padEnd(18)} ${s.title}`); return 0; }
  const env = loadEnv();
  const model = args.model || env.OPENAI_TEXT_MODEL;
  const src = loadUxSources();
  const plan = planRun({ src, model, only: args.only || null });
  const allowed = allowedTokenNames(src);

  if (args['dry-run']) {
    log(`DRY RUN - nothing is sent. ${plan.requests.length} request(s) to ${OPENAI_RESPONSES_URL} (model ${model}).`);
    log('\n### developer (system) prompt\n' + plan.system);
    for (const r of plan.requests) {
      const file = writeDryRun(shapeDryRun({ tool: 'openai-uxui', name: r.name, url: OPENAI_RESPONSES_URL, headers: openaiHeaders('<OPENAI_API_KEY>'), body: r.body, outputs: [OUT_JSON, OUT_MD], notes: [HEADER] }));
      log(`\n### ${r.name} -> ${file}\n` + r.body.input[1].content[0].text);
    }
    log(`\nKey status: OPENAI_API_KEY ${env.OPENAI_API_KEY ? 'present' : 'EMPTY (fill .env before a real run)'}`);
    return 0;
  }

  const key = requireKey(env, 'OPENAI_API_KEY');
  const report = { note: HEADER, tool: 'tools/ai/openai-uxui.js', model, createdAt: new Date().toISOString(), allowedTokens: allowed, usage: [], screens: [], errors: [] };
  for (const r of plan.requests) {
    log(`-> ${r.name}`);
    try {
      const res = await postJson(OPENAI_RESPONSES_URL, { headers: openaiHeaders(key), body: r.body, timeoutMs: 240000 });
      report.usage.push({ request: r.name, ...usageOf(res) });
      const data = parseStructured(res);
      const errors = validateSchema(SCREEN_SCHEMA, data);
      if (errors.length) throw new Error(`response failed schema validation: ${errors.slice(0, 5).join('; ')}`);
      report.screens.push({ id: r.screen.id, app: r.screen.app, title: r.screen.title, current: r.screen.current, proposal: data, review: reviewScreen(data, allowed) });
    } catch (e) { const msg = `${r.name}: ${redact(e.message)}`; report.errors.push(msg); warn(`FAILED ${msg}`); }
  }
  writeJson(OUT_JSON, report);
  writeText(OUT_MD, renderMarkdown(report));
  log(`Wrote ${OUT_JSON} and ${OUT_MD}: ${report.screens.length} screen(s), ${report.errors.length} error(s). apps/ untouched.`);
  return report.errors.length ? 1 : 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().then((code) => process.exit(code)).catch((e) => { warn(`error: ${redact(e.message)}`); process.exit(1); });
}
