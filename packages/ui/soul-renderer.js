// Arise Soul renderer v5 - the Arise Soul baseline character (D-27, docs/art/soul-baseline.md) as a flat sticker SVG in
// the "Arise Soul x AriSkill" sticker language (stage 10 / D-25, BR-16/BR-17; spec: docs/art/sticker-art-direction.md),
// decorated since stage 12 (D-29, docs/art/soul-decorations.md) with a body gradient, a face kit and 10 skill charms,
// and since stage 13 (D-31, docs/art/soul-faces.md) with a face plate, eyes and an antenna charm on the v3 body.
// The drawing is the front view of the 3D model: every baseline coordinate comes from ./soul-baseline-shape.js, which
// tools/assets/build-soul-shape.py projects out of tools/ai/blender/soul_baseline.py (the same signed-distance model
// that builds the GLBs), so thumbnails, Galaxy sprites and fallbacks show the same character as the 3D scenes. Charm
// slots and sprite files come from ./soul-decor-data.js (generated by tools/ai/blender/soul_decor.py); the v3 outline,
// plate / eyes / face-kit sprites and the antenna-charm slot from ./soul-face-data.js (tools/ai/blender/soul_face.py);
// colours, charm ids and the names screen readers hear from the catalog (packages/game-rules/src/soul-catalog.js).
// ESM, no DOM, pure-data imports; runs in browsers and Node >= 24. Same input -> byte-identical output.
//
// Config versions:
//   - v1 (Souls created before stage 12): palette + glow + badge, drawn exactly as renderer 3.0.0 (byte-identical);
//   - v2 { version: 2, gradient, glow, face, charms[10] }, drawn exactly as renderer 4.0.0 (byte-identical): the body
//     gradient as a vertical linearGradient over the catalog's gradientSpan (the 2D stand-in for the per-vertex fill of
//     the 3D tint, sRGB interpolation like the 3D mix), drips / eyes / orb coloured from the gradient entry, then the
//     face sprite and the charm sprites as <image> layers at the decor data's front2d positions (opts.images: false
//     omits them for data: URL rasterisation, and soulSpriteLayers() hands them to canvas compositing instead). The
//     Bingo Star badge gets a round medallion backing so it never reads as a core star charm;
//   - v3 { version: 3, ...v2, plate, eyes, topper } (contract 1.2.0 on): the same gradient body on the v3 outline
//     (SOUL_FACE.shape.silhouette: no orb, no button eyes), then the sprites in paint order plate, eyes, face kit (each
//     at its data rect), the 10 charms (as v2) and the antenna charm (its charm PNG 2 r wide on SOUL_FACE.topper.front2d).
//     While the face data is unusable (the checked-in stub) a v3 Soul is drawn exactly as the v2 Soul with the same
//     gradient, face kit and charms (baseline outline, button eyes, orb), so it never looks broken.
//
// Inclusivity invariants (docs/art/soul-system.md, D-27, D-29, D-31):
//   - every Soul is the same character, drawn in the same 200x200 viewBox at the same scale and line weights;
//   - per player only the colour (8 palettes / 12 gradients, one luminance band), the glow style (3, equal peak
//     opacity), the face (3, equal weight), the charms (one size), the face plate, eyes and antenna charm (seeded,
//     never from skills) and the separate Bingo Star badge vary. The seeded body/eyes/antenna/mouth traits of v1 and
//     the constellation stay in the config but are not drawn;
//   - Platform, Role, matrix alignment, rank, counts and winner status are NOT inputs (the badge is a separate flag).
//
// Look (all detail levels except 'dot'): clay body (v1: palette light top-left -> base -> violet-deep at the bottom
// edge; v2 and v3: the body gradient with the same light and shade laid over it) with a thin outline, peach rim light
// lower-right, chin crease and arm slits, goo drips in the light colour with a soft edge, near-white button eyes ringed
// by a groove in the outline colour and the antenna neck with a lit orb and its glow (v1, v2; the v3 face plate, eyes
// and antenna charm are sprites), a soft key-light highlight, and the white die-cut outline + soft shadow behind the
// whole figure. 'simple' keeps the die-cut at 3 px (at 240 px) and drops every filter (flat offset shadow, crisp drips)
// so thumbnails and the Galaxy atlas stay cheap.
