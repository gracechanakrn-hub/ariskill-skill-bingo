/**
 * "an" before a vowel sound, else "a", for a catalog name: a, e, i, o and a u that is not read "you" (an umbrella, a
 * unicorn); a word in capitals is read letter by letter, so it goes by its first letter's name (a USB stick, an LED).
 * Tested on every plate and charm name of the catalog.
 */
export function indefiniteArticle(phrase) {
  const word = String(phrase).trim().split(/[\s-]/)[0];
  if (/^[A-Z]{2,}$/.test(word)) return 'AEFHILMNORSX'.includes(word[0]) ? 'an' : 'a';
  return /^(?:[aeio]|u(?![bcdfghjklmnpqrstvwxyz][aeiouy]))/i.test(word) ? 'an' : 'a';
}

/**
 * A charm as the alt text names it: its catalog name, except that a "shape, shade" star name reads shade first, the
 * way it is said ("classic star, lemon" -> "lemon classic star"). null for an unknown id.
 */
export function charmAltName(id) {
  const ch = CHARM_BY_ID.get(id);
  if (!ch) return null;
  const m = /^(.+), (.+)$/.exec(ch.name);
  return m ? `${m[2]} ${m[1]}` : ch.name;
}

/** "a", "a and b", "a, b and c"; the list gets a serial comma when an item already reads "x and y" (so it stays three items). */
function listText(items) {
  if (items.length < 3) return items.join(' and ');
  const serial = items.some((i) => i.includes(' and ')) ? ',' : '';
  return `${items.slice(0, -1).join(', ')}${serial} and ${items[items.length - 1]}`;
}

/** ". 10 charms: 4 technical, 4 core, 2 soft" (kinds with charms only, in ALT_KIND_ORDER), or '' without charms. */
function charmsAlt(charms) {
  if (!charms.length) return '';
  const count = (k) => charms.filter((c) => c.kind === k).length;
  const kinds = ALT_KIND_ORDER.filter((k) => count(k) > 0).map((k) => `${count(k)} ${k}`).join(', ');
  return `. ${charms.length} charm${charms.length === 1 ? '' : 's'}: ${kinds}`;
}

/**
 * Accessible description of the Soul (from its config, like the charm counts: a piece whose file is missing is still
 * named). Never mentions Platform, Role, rank, capability or a skill. v3: "Arise Soul, Aurora colour, with a bean face,
 * heart eyes and round glasses. 10 charms: 4 technical, 4 core, 2 soft. A lemon classic star charm on its antenna".
 */
export function soulAltText(config, badge = null) {
  const s = resolveSoul(config);
  let t;
  if (s.version === 3) {
    // The charm counts and the antenna charm get their own sentences, as in v2 (the look list already reads "x and y").
    const plate = PLATE_NAME.get(s.plate);
    const look = [plate && `${indefiniteArticle(plate)} ${plate} face`, EYES_NAME.get(s.eyes), FACE_ALT_V3[s.face]].filter(Boolean);
    t = `Arise Soul, ${s.grad.name} colour${look.length ? `, with ${listText(look)}` : ''}${charmsAlt(s.charms)}`;
    const topper = s.topper && charmAltName(s.topper.id);
    if (topper) { const a = indefiniteArticle(topper); t += `. ${a[0].toUpperCase()}${a.slice(1)} ${topper} charm on its antenna`; }
  } else if (s.version === 2) {
    // The charms get their own sentence: face kits already read "x and y", so one sentence would chain two "and"s.
    const face = s.face ? FACE_ALT[s.face] : s.charms.length ? 'round button eyes' : 'round button eyes and a glowing antenna orb';
    t = `Arise Soul, ${s.grad.name} colour, with ${face}${charmsAlt(s.charms)}`;
  } else {
    t = `Arise Soul, ${s.palette} colour, with round button eyes and a glowing antenna orb`;
  }
  if (badge === 'bingo-star') t += '. Bingo Star badge: completed a line this round';
  return t;
}

