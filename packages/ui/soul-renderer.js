/** Small deterministic 32-bit string hash (FNV-1a with a final avalanche). Own implementation, no imports. */
export function hash32(str) {
  let h = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) { h ^= str.charCodeAt(i); h = Math.imul(h, 0x01000193); }
  h ^= h >>> 16; h = Math.imul(h, 0x7feb352d); h ^= h >>> 15; h = Math.imul(h, 0x846ca68b); h ^= h >>> 16;
  return h >>> 0;
}

function traitName(kind, value) {
  const list = TRAITS[kind];
  if (typeof value === 'string' && list.includes(value)) return value;
  const i = Number.isInteger(value) ? value : 0;
  return list[((i % list.length) + list.length) % list.length];
}

function esc(s) { return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;'); }
function n(v) { return Number(v.toFixed(1)).toString(); }
const hex2 = (v) => Math.round(v).toString(16).toUpperCase().padStart(2, '0');
/** sRGB midpoint of two '#RRGGBB' colours (the gradient's representative fill for the dot level and glow-free uses). */
function midHex(a, b) {
  const p = (h, i) => parseInt(h.slice(1 + i * 2, 3 + i * 2), 16);
  return '#' + [0, 1, 2].map((i) => hex2((p(a, i) + p(b, i)) / 2)).join('');
}

function starPath(cx, cy, outer, inner, points = 5) {
  let d = '';
  for (let i = 0; i < points * 2; i++) {
    const r = i % 2 === 0 ? outer : inner;
    const a = -Math.PI / 2 + (i * Math.PI) / points;
    d += (i ? 'L' : 'M') + n(cx + r * Math.cos(a)) + ' ' + n(cy + r * Math.sin(a));
  }
  return d + 'Z';
}

/** True for a decorated (v2+) config; v1 and anything without a version keep the palette path. */
export function isDecoratedConfig(config) { return !!config && typeof config === 'object' && Number(config.version) >= 2; }

/**
 * Normalised config: trait names + palette object. Accepts indices or names. v2 configs also resolve `gradient`
 * (index), `grad` (catalog entry), `face` (a catalog face or null) and `charms` ([{ slot, id, kind }], known ids only,
 * slot = index); their `pal` is the gradient seen as a palette (fill = sRGB midpoint of top and bottom) so every glow /
 * outline lookup works for both versions. v3 configs add `plate` and `eyes` (catalog ids or null; `eyes` replaces the
 * v1 eye trait) and `topper` ({ id, kind } of the antenna charm, or null when unknown or one of the body charms).
 * Unknown values fall back instead of throwing.
 */
export function resolveSoul(config = {}) {
  const c = config || {};
  const body = traitName('body', c.body), palette = traitName('palette', c.palette), eyes = traitName('eyes', c.eyes);
  const antenna = traitName('antenna', c.antenna), mouth = traitName('mouth', c.mouth), glow = traitName('glow', c.glow);
  const pal = PALETTES[TRAITS.palette.indexOf(palette)];
  const constellation = Array.isArray(c.constellation) ? c.constellation.slice(0, 5) : [];
  const driftPhase = typeof c.driftPhase === 'number' && Number.isFinite(c.driftPhase) ? Math.min(1, Math.max(0, c.driftPhase)) : 0;
  const base = { seed: String(c.seed ?? 'soul'), body, palette, eyes, antenna, mouth, glow, pal, constellation, driftPhase };
  if (!isDecoratedConfig(c)) return { ...base, version: 1 };
  const gradient = Number.isInteger(c.gradient) && c.gradient >= 0 && c.gradient < GRADIENTS.length ? c.gradient : 0;
  const grad = GRADIENTS[gradient];
  const face = FACES.includes(c.face) ? c.face : null;
  const charms = [];
  if (Array.isArray(c.charms)) c.charms.slice(0, SLOT_COUNT).forEach((id, slot) => { const ch = CHARM_BY_ID.get(id); if (ch) charms.push({ slot, id: ch.id, kind: ch.kind }); });
  const out = {
    ...base, version: 2, palette: grad.id, gradient, grad, face, charms,
    pal: { name: grad.id, fill: midHex(grad.top, grad.bottom), highlight: grad.highlight, outline: grad.outline, glow: grad.glow },
  };
  if (Number(c.version) >= 3) {
    // v3 (stage 13, D-31, docs/art/soul-faces.md): face plate, eyes and the antenna charm; unknown ids resolve to null
    const top = CHARM_BY_ID.get(c.topper);
    out.version = 3;
    out.plate = PLATE_IDS.includes(c.plate) ? c.plate : null;
    out.eyes = EYE_IDS.includes(c.eyes) ? c.eyes : null;
    out.topper = top && !charms.some((ch) => ch.id === top.id) ? { id: top.id, kind: top.kind } : null;
  }
  return out;
}

