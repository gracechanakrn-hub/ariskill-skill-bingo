/** Goo drips: round-capped strokes grouped by width (capsules measured on the 3D drip mask); colour comes from <use>. */
const DRIPS = DRIP_STROKES.map(([w, d]) => `<path stroke-width="${w}" d="${d}"/>`).join('');

/** Figure frame (feet .. antenna orb) from the baseline shape; the ambient glow is centred on the figure. */
const FIG = Object.freeze({ cx: (BOUNDS.x0 + BOUNDS.x1) / 2, cy: (BOUNDS.y0 + BOUNDS.y1) / 2 });
const GLOW_R = 86;

function glowSvg(kind, pal, id, motion, phase) {
  const anim = motion ? `<animate attributeName="opacity" values=".78;1;.78" dur="4.8s" begin="-${n(phase * 4.8)}s" repeatCount="indefinite"/>` : '';
  const cy = n(FIG.cy + 8);
  let s = `<circle cx="100" cy="${cy}" r="${GLOW_R}" fill="url(#${id}-g)">${anim}</circle>`;
  if (kind === 'ring') s += `<circle cx="100" cy="${cy}" r="80" fill="none" stroke="${pal.glow}" stroke-width="1.6" stroke-dasharray="10 6" opacity=".42"/>`;
  if (kind === 'halo') s += `<ellipse cx="${ORB.cx}" cy="${n(BOUNDS.y0 - 11)}" rx="17" ry="4" fill="none" stroke="${pal.highlight}" stroke-width="3" opacity=".85"/>`;
  return s;
}

/**
 * Button eyes: near-white disc ringed by the groove in the palette outline colour (both measured on the 3D model).
 * The model's eyes are mirror images, so the viewer's left eye is drawn once and mirrored about x = 100.
 */
function eyesSvg(pal, id) {
  const e = EYES[0];
  return `<g id="${id}-e" transform="translate(${e.cx} ${e.cy}) rotate(${e.rot})"><ellipse rx="${e.rx}" ry="${e.ry}" fill="${EYE_WHITE}"/>` +
    `<ellipse rx="${e.ring.rx}" ry="${e.ring.ry}" fill="none" stroke="${pal.outline}" stroke-width="${n(Math.max(1.3, e.ring.w))}"/></g>` +
    `<use href="#${id}-e" transform="matrix(-1 0 0 1 ${VIEWBOX} 0)"/>`; // x -> 200 - x (the model axis is x = 100)
}

export const BADGE_LABEL = 'Bingo Star badge: completed a line this round';
/** Bingo Star: gold five-point star with a white die-cut outline, upper right, clear of the head and the antenna orb. */
export const BADGE_CENTER = Object.freeze({ cx: 166, cy: 38, r: 13 });
/**
 * v2 Bingo Star: the same gold star on a round medallion (violet-deep disc, white die-cut, gold inner ring), so it can't
 * be mistaken for a core star charm (charms are unbacked pastel stars on the body).
 */
export const BADGE_MEDALLION = Object.freeze({ r: 15.5, star: 10.4 });
function badgeSvg(medallion = false) {
  const { cx, cy, r } = BADGE_CENTER;
  if (!medallion) {
    return `<g role="img" aria-label="${BADGE_LABEL}" transform="translate(${cx} ${cy})"><title>${BADGE_LABEL}</title><path d="${starPath(0, 0.6, r, r * 0.46)}" fill="${STICKER.gold}" stroke="#fff" stroke-width="2.6" stroke-linejoin="round"/><path d="${starPath(-1.4, -1, 6.2, 2.8)}" fill="#FFF0B3" opacity=".75"/></g>`;
  }
  const M = BADGE_MEDALLION;
  return `<g role="img" aria-label="${BADGE_LABEL}" transform="translate(${cx} ${cy})"><title>${BADGE_LABEL}</title>` +
    `<circle r="${M.r}" fill="${STICKER.violetDeep}" stroke="#fff" stroke-width="2.6"/><circle r="${n(M.r - 3.2)}" fill="none" stroke="${STICKER.gold}" stroke-width="1.2" opacity=".9"/>` +
    `<path d="${starPath(0, 0.5, M.star, M.star * 0.46)}" fill="${STICKER.gold}" stroke-linejoin="round"/><path d="${starPath(-1.1, -0.8, 5, 2.3)}" fill="#FFF0B3" opacity=".75"/></g>`;
}

