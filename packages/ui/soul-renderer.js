/**
 * Render a Soul as a complete <svg> string.
 * @param {object} config SoulConfig v1, v2 or v3 (indices or names) - see packages/game-rules/src/soul.js
 * @param {object} opts { size=160, badge=null|'bingo-star', detail='full'|'simple'|'dot', reducedMotion=false, label=null, idPrefix, images=true, decor, face }
 *   size          CSS px of the square output (viewBox is always 200); the die-cut and shadow scale with it.
 *   badge         'bingo-star' draws the gold star (upper right; on a medallion for v2+); never part of the config (BR-17).
 *   detail        'full' = gradients, filters (soft drips, highlight blur, drop shadow), ambient glow style, optional
 *                 glow breath; 'simple' = same character without filters (3 px die-cut, flat offset shadow) for
 *                 thumbnails / the Galaxy atlas; 'dot' = 24 px glowing disc for very dense Galaxies (no badge).
 *   images        v2+ only: false omits the sprite <image> layers (data: URL rasterisation cannot load them;
 *                 composite soulSpriteLayers() instead). 'dot' never has them.
 *   decor         the decor data (default ./soul-decor-data.js); unusable data (the stub) draws no charms or v2 face kit.
 *   face          the v3 face data (default ./soul-face-data.js); unusable data (the stub) draws v3 Souls as v2 Souls.
 *   reducedMotion removes the glow breath <animate>; label overrides the alt text; idPrefix namespaces defs ids.
 */
export function renderSoulSvg(config, opts = {}) {
  const { size = 160, badge = null, detail = 'full', reducedMotion = false, label = null, idPrefix, images = true, decor = SOUL_DECOR, face = SOUL_FACE } = opts;
  const s = resolveSoul(config);
  const pal = s.pal;
  const decorated = s.version >= 2;               // v2+: gradient body, soft glow for halo, medallion badge
  const v3 = s.version === 3 && faceUsable(face); // the v3 body: its own outline, no button eyes, no antenna orb
  const id = idPrefix || `soul-${s.seed.replace(/[^A-Za-z0-9_-]/g, '')}`;
  const alt = esc(label || soulAltText(config, detail === 'dot' ? null : badge)); // dot never draws the badge
  const open = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${VIEWBOX} ${VIEWBOX}" width="${size}" height="${size}" role="img" aria-label="${alt}" data-soul="${esc(s.seed)}" data-detail="${detail}">`;

  if (detail === 'dot') {
    return open + `<defs><radialGradient id="${id}-g"><stop offset="0" stop-color="${pal.glow}" stop-opacity=".9"/><stop offset=".45" stop-color="${pal.glow}" stop-opacity=".35"/><stop offset="1" stop-color="${pal.glow}" stop-opacity="0"/></radialGradient></defs>` +
      `<circle cx="100" cy="100" r="90" fill="url(#${id}-g)"/><circle cx="100" cy="100" r="26" fill="${pal.fill}" stroke="${pal.outline}" stroke-width="6"/><circle cx="100" cy="100" r="11" fill="${pal.highlight}"/></svg>`;
  }

  const full = detail !== 'simple';
  const sh = STICKER.shadow, W = '#fff'; // short form of STICKER.outline (#FFFFFF) in the markup
  const clip = `clip-path="url(#${id}-c)"`;
  // body fill: v1 the clay radial (palette light -> base -> violet-deep); v2+ the vertical body gradient over the span
  // (y from the gradient top down to the floor) with the same light / shade as a separate overlay (-s)
  const bodyFill = decorated
    ? `<linearGradient id="${id}-b" gradientUnits="userSpaceOnUse" x1="0" y1="${gradientY(GRADIENT_SPAN.top)}" x2="0" y2="${gradientY(GRADIENT_SPAN.bottom)}"><stop offset="0" stop-color="${s.grad.top}"/><stop offset="1" stop-color="${s.grad.bottom}"/></linearGradient>` +
      `<radialGradient id="${id}-s" cx=".4" cy=".3" r="1.05"><stop offset=".05" stop-color="#fff" stop-opacity=".55"/><stop offset=".55" stop-color="#fff" stop-opacity="0"/><stop offset=".62" stop-color="${STICKER.violetDeep}" stop-opacity="0"/><stop offset="1" stop-color="${STICKER.violetDeep}" stop-opacity=".6"/></radialGradient>`
    : `<radialGradient id="${id}-b" cx=".4" cy=".3" r="1.05"><stop offset=".05" stop-color="${pal.highlight}"/><stop offset=".6" stop-color="${pal.fill}"/><stop offset="1" stop-color="${STICKER.violetDeep}"/></radialGradient>`;
  // defs: silhouette (reused by clip + die-cut + fill + rim; v3: the face data's outline), drips, body gradient, rim
  // gradient, orb glow (not v3), ambient glow, filters
  let defs = `<defs><path id="${id}-p" d="${v3 ? face.shape.silhouette : SILHOUETTE}"/><g id="${id}-q" stroke-linecap="round">${DRIPS}</g>` +
    `<clipPath id="${id}-c"><use href="#${id}-p"/></clipPath>` + bodyFill +
    `<linearGradient id="${id}-r" x2="1" y2="1"><stop offset=".45" stop-color="${STICKER.peach}" stop-opacity="0"/><stop offset="1" stop-color="${STICKER.peach}" stop-opacity=".4"/></linearGradient>` +
    (v3 ? '' : `<radialGradient id="${id}-o"><stop offset="0" stop-color="#fff"/><stop offset=".45" stop-color="${pal.highlight}"/><stop offset="1" stop-color="${pal.highlight}" stop-opacity="0"/></radialGradient>`);
  if (full) {
    defs += `<radialGradient id="${id}-g"><stop offset="0" stop-color="${pal.glow}" stop-opacity=".55"/><stop offset=".55" stop-color="${pal.glow}" stop-opacity=".18"/><stop offset="1" stop-color="${pal.glow}" stop-opacity="0"/></radialGradient>` +
      `<filter id="${id}-d" x="-.3" y="-.2" width="1.6" height="1.45"><feDropShadow dx="0" dy="${n(sh.dy * REF_PX)}" stdDeviation="${n((sh.blur / 2) * REF_PX)}" flood-color="${sh.color}" flood-opacity="${sh.opacity}"/></filter>` +
      `<filter id="${id}-h" x="-.5" y="-.5" width="2" height="2"><feGaussianBlur stdDeviation="${n(2 * REF_PX)}"/></filter>` +
      `<filter id="${id}-k"><feGaussianBlur stdDeviation=".3"/></filter>`;
  }
  defs += '</defs>';

  // die-cut: the whole figure as a white stroke + shadow (full: soft drop shadow; simple: flat offset copy)
  const dieCut = full
    ? `<use href="#${id}-p" fill="${W}" stroke="${W}" stroke-width="${n(DIECUT_FULL)}" stroke-linejoin="round" filter="url(#${id}-d)"/>`
    : `<use href="#${id}-p" fill="${sh.color}" stroke="${sh.color}" stroke-width="${n(DIECUT_SIMPLE)}" stroke-linejoin="round" transform="translate(0 ${n(sh.dy * REF_PX)})" opacity=".45"/>` +
      `<use href="#${id}-p" fill="${W}" stroke="${W}" stroke-width="${n(DIECUT_SIMPLE)}" stroke-linejoin="round"/>`;
  const orbGlow = v3 ? '' : `<circle cx="${ORB.cx}" cy="${ORB.cy}" r="${n(ORB.r * 2.2)}" fill="url(#${id}-o)"/>`;
  const bodySvg = decorated
    ? `<use href="#${id}-p" fill="url(#${id}-b)"/><use href="#${id}-p" fill="url(#${id}-s)"/><use href="#${id}-p" fill="none" stroke="${pal.outline}" stroke-width="${BODY_LINE}" stroke-linejoin="round"/>`
    : `<use href="#${id}-p" fill="url(#${id}-b)" stroke="${pal.outline}" stroke-width="${BODY_LINE}" stroke-linejoin="round"/>`;
  const rim = `<use href="#${id}-p" fill="none" stroke="url(#${id}-r)" stroke-width="${n(2 * REF_PX * 2)}" ${clip}/>`;
  // chin crease + arm slits: a soft fold shade in the palette outline colour (a blurred band at full detail, so the
  // crease reads as the fold under the head, never as a mouth line)
  const lines = `<path d="${LINES}" fill="none" stroke="${pal.outline}" stroke-width="${full ? 4 : 3}" stroke-linecap="round" opacity="${full ? '.25' : '.22'}"${full ? ` filter="url(#${id}-h)"` : ''}/>`;
  // goo drips: a faint contact shade below each blob, then the blob in the palette light (soft edge at full detail)
  const drips = `<g ${clip}><use href="#${id}-q" stroke="${pal.outline}" opacity=".2" transform="translate(.4 1)"/>` +
    `<use href="#${id}-q" stroke="${pal.highlight}"${full ? ` filter="url(#${id}-k)"` : ''}/></g>`;
  const [hx, hy, hrx, hry, hrot] = HIGHLIGHTS[0];
  const highlight = `<ellipse cx="${hx}" cy="${hy}" rx="${n(hrx * 1.5)}" ry="${n(hry * 1.2)}" transform="rotate(${hrot} ${hx} ${hy})" fill="#fff" opacity="${full ? '.3' : '.2'}"${full ? ` filter="url(#${id}-h)"` : ''}/>`;
  // button eyes and the antenna orb belong to the baseline body; the v3 face plate, eyes and antenna charm are sprites
  const eyes = v3 ? '' : eyesSvg(pal, id);
  const orb = v3 ? '' : `<circle cx="${ORB.cx}" cy="${ORB.cy}" r="${ORB.r}" fill="${pal.highlight}" stroke="${pal.outline}" stroke-width="1.6"/><circle cx="${ORB.spec.x}" cy="${ORB.spec.y}" r="2.6" fill="#fff"/>`;
  // A decorated Soul (v2+) never draws the halo glow style (a ring above the antenna): the angel face kit's halo means
  // soft skills (D-29), so any other ring there would read as one. Those Souls take the soft glow instead.
  const ambient = full ? glowSvg(decorated && s.glow === 'halo' ? 'soft' : s.glow, pal, id, !reducedMotion, s.driftPhase) : '';
  const decorations = decorated && images ? imagesSvg(spriteLayers(s, decor, face)) : '';

  return open + defs + ambient + orbGlow + dieCut + bodySvg + rim + lines + drips + highlight + eyes + orb + decorations +
    (badge === 'bingo-star' ? badgeSvg(decorated) : '') + '</svg>';
}

/**
 * Deterministic orbit slot for a Soul. `count` = number of Souls currently in the Galaxy (opens rings from the inside out).
 * Returns { ring, slot, capacity, radius, angle } - angle in radians, slot-centred with a small per-Soul jitter.
 */
export function soulOrbitSlot(soulId, count = 1) {
  const id = String(soulId);
  const need = Math.max(1, Math.floor(count) || 1);
  let active = 0, cum = 0;
  while (active < ORBIT_RINGS.length && cum < need) { cum += ORBIT_RINGS[active].capacity; active++; }
  const pick = hash32(id + ':ring') % cum;
  let ring = 0, acc = 0;
  for (let i = 0; i < active; i++) { acc += ORBIT_RINGS[i].capacity; if (pick < acc) { ring = i; break; } }
  const r = ORBIT_RINGS[ring];
  const slot = hash32(id + ':slot') % r.capacity;
  const jitter = ((hash32(id + ':jitter') % 1000) / 1000 - 0.5) * 0.5; // +-0.25 slot width
  const angle = ((slot + 0.5 + jitter) / r.capacity) * Math.PI * 2;
  return { ring, slot, capacity: r.capacity, radius: r.radius, angle };
}

export default renderSoulSvg;
