/**
 * True when the decor data can be drawn: generated (never the hand-written stub, whose values must not ship), with
 * slots, charm files and face files. Otherwise decorated Souls render as the plain gradient Soul.
 */
export function decorUsable(decor = SOUL_DECOR) {
  return !!(decor && decor.stub !== true && Array.isArray(decor.slots) && decor.slots.length > 0 &&
    decor.charm && decor.charm.files && typeof decor.charm.files === 'object' && decor.faces && typeof decor.faces === 'object');
}

/** SVG path data only (commands, numbers, separators), so a generated outline can go into d="" as it is. */
const PATH_DATA = /^[Mm][MmZzLlHhVvCcSsQqTtAaEe\d\s.,+-]*$/;
const isMap = (m) => !!m && typeof m === 'object';

/**
 * True when the v3 face data can be drawn: generated (never the stub placeholder written before the first build), with
 * the v3 outline as path data and the plate, eyes and face-kit file maps. Otherwise v3 Souls render as the v2 Soul with
 * the same gradient, face kit and charms. A single piece without a usable file or rect is skipped on its own.
 */
export function faceUsable(face = SOUL_FACE) {
  return !!(face && face.stub !== true && face.shape && typeof face.shape.silhouette === 'string' &&
    PATH_DATA.test(face.shape.silhouette) && isMap(face.plates) && isMap(face.eyes) && isMap(face.faces));
}

/**
 * Sprite layers of a decorated Soul in paint order, in viewBox units. v2 (and v3 while the face data is unusable): the
 * face kit over the whole viewBox, then the charms by slot. v3: the face plate, the eyes and the face kit at their data
 * rects, the charms by slot, then the antenna charm 2 r wide centred on SOUL_FACE.topper.front2d:
 * [{ kind: 'plate', plate, ... } | { kind: 'eyes', eyes, ... } | { kind: 'face', face, ... } | { kind: 'charm', slot,
 * id, ... } | { kind: 'topper', id, ... }], each with href, x, y, w, h. A piece without a file (charm.missing
 * included), slot or rect is left out on its own; v1 configs, the neutral fallback and unusable decor data have no charm
 * layers. The atlas draws these over the rasterised SVG (SVG-as-image cannot load external images); inline SVG gets
 * them as <image> elements.
 */
export function soulSpriteLayers(config, { decor = SOUL_DECOR, face = SOUL_FACE } = {}) { return spriteLayers(resolveSoul(config), decor, face); }

function spriteLayers(s, decor, faceData) {
  if (s.version === 3 && faceUsable(faceData)) return faceLayers(s, decor, faceData);
  if (s.version < 2 || !decorUsable(decor)) return [];
  const out = [];
  const box = Number(decor.sprite2d && decor.sprite2d.viewBox) || VIEWBOX;
  const faceFile = s.face && decor.faces[s.face];
  if (faceFile && faceFile.sprite) out.push({ kind: 'face', face: s.face, href: faceFile.sprite, x: 0, y: 0, w: box, h: box });
  return out.concat(charmLayers(s.charms, decor));
}

/** v3 layers: plate, eyes and face kit from the face data, then the charms and the antenna charm (SOUL_DECOR files). */
function faceLayers(s, decor, faceData) {
  const out = [];
  for (const [kind, files, id] of [['plate', faceData.plates, s.plate], ['eyes', faceData.eyes, s.eyes], ['face', faceData.faces, s.face]]) {
    const file = id ? files[id] : null;
    const at = file && typeof file.sprite === 'string' && file.sprite ? rectOf(file.rect) : null;
    if (at) out.push({ kind, [kind]: id, href: file.sprite, ...at });
  }
  if (!decorUsable(decor)) return out;
  out.push(...charmLayers(s.charms, decor));
  const file = s.topper && charmFile(decor, s.topper.id);
  const at = file && faceData.topper ? discOf(faceData.topper.front2d) : null;
  if (at) out.push({ kind: 'topper', id: s.topper.id, href: file.png, ...at });
  return out;
}

/** The charms at their decor slots (v2 and v3), by slot. */
function charmLayers(charms, decor) {
  const out = [];
  for (const ch of charms) {
    const slot = decor.slots.find((sl) => sl.index === ch.slot) || decor.slots[ch.slot];
    const file = charmFile(decor, ch.id);
    const at = file && slot ? discOf(slot.front2d) : null;
    if (at) out.push({ kind: 'charm', slot: ch.slot, id: ch.id, href: file.png, ...at });
  }
  return out;
}

/** A charm's files when its PNG is built (charm.missing: not built yet, skipped), else null. */
function charmFile(decor, id) {
  const notBuilt = Array.isArray(decor.charm.missing) ? decor.charm.missing : [];
  const file = notBuilt.includes(id) ? null : decor.charm.files[id];
  return file && file.png ? file : null;
}

const r2 = (v) => Number(v.toFixed(2));
/** A charm disc { x, y, r } (viewBox) as the square its PNG fills (the outline is the image's inscribed circle), or null. */
function discOf(p) {
  if (!p || !Number.isFinite(p.x) || !Number.isFinite(p.y) || !(p.r > 0)) return null;
  return { x: r2(p.x - p.r), y: r2(p.y - p.r), w: r2(2 * p.r), h: r2(2 * p.r) };
}
/** A data rect [x, y, w, h] (viewBox) as layer fields, or null unless it is four finite numbers with w, h > 0. */
function rectOf(rect) {
  if (!Array.isArray(rect) || rect.length !== 4 || !rect.every((v) => Number.isFinite(v)) || !(rect[2] > 0 && rect[3] > 0)) return null;
  const [x, y, w, h] = rect.map(r2);
  return { x, y, w, h };
}

/** <image> per layer; x / y are left out at the origin (the full-viewBox v2 face sprite, as renderer 4.0.0 wrote it). */
function imagesSvg(layers) {
  return layers.map((l) => `<image href="${esc(l.href)}"${l.x || l.y ? ` x="${l.x}" y="${l.y}"` : ''} width="${l.w}" height="${l.h}"/>`).join('');
}

