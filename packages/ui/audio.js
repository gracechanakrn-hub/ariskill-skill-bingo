// packages/ui/audio.js - AriSkill Skill Bingo AudioManager (browser ESM, zero dependencies).
//
// Design rules (docs/audio/sound-spec.md):
//   * Sound never carries required information: every play() request emits a caption event,
//     whether or not audio actually played, so apps can render the visual/live-region equivalent.
//   * Honors browser autoplay policy: nothing plays until unlock() succeeds inside a user gesture.
//   * Fails silently: no method ever throws; missing files, decode errors, denied autoplay and
//     absent AudioContext (E14) all degrade to "unavailable" and return false.
//   * Safe under rapid events: per-cue rate limits, max 4 concurrent voices with priority stealing,
//     replayed events (fresh === false, or sequence <= connection epoch) never play.
//   * Importable in Node: no top-level access to window, document, Audio or AudioContext.
//
// Cue policy below mirrors assets/manifest/audio.json (canonical: assets/manifest/audio.yaml,
// generated by tools/assets/build-audio.py). tools/assets/test/audio.test.js fails if they drift.

export const AUDIO_MANIFEST_VERSION = '1.0.0';
export const DEFAULT_BASE_URL = '/assets/audio';
export const DEFAULT_MANIFEST_URL = '/assets/manifest/audio.json';
export const MAX_VOICES = 4;

