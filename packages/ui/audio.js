// Which cues each app should preload right after createAudioManager() (spec section 6).
export const PRELOAD_BY_APP = Object.freeze({
  participant: ['draw_reveal', 'cell_match', 'bingo', 'float_launch', 'float_countdown', 'draw5_unlock'],
  public:      ['ambient_galaxy', 'draw_reveal', 'bingo', 'float_launch', 'draw_leadin', 'draw5_unlock'],
  stage:       ['ambient_galaxy', 'draw_reveal', 'bingo', 'float_launch'],
  admin:       ['draw_reveal', 'bingo'],
});

const STORAGE_PREFIX = 'ariskill-skill-bingo:audio:';
const AMBIENT_FADE_IN_S = 1.5;
const AMBIENT_FADE_OUT_S = 0.8;

function clamp01(v) { const n = Number(v); return Number.isFinite(n) ? Math.min(1, Math.max(0, n)) : 1; }
function dbToLin(db) { return Math.pow(10, Number(db || 0) / 20); }
function toMs(at) {
  if (at == null) return null;
  if (typeof at === 'number') return Number.isFinite(at) ? at : null;
  if (at instanceof Date) return at.getTime();
  const p = Date.parse(String(at));
  return Number.isFinite(p) ? p : null;
}
function nowMs() {
  try { if (globalThis.performance && typeof globalThis.performance.now === 'function') return globalThis.performance.now(); } catch (_) { /* ignore */ }
  return Date.now();
}
function later(fn, ms) {
  try {
    if (typeof globalThis.setTimeout !== 'function') return null;
    const t = globalThis.setTimeout(fn, ms);
    if (t && typeof t.unref === 'function') t.unref(); // Node: never keep a test process alive
    return t;
  } catch (_) { return null; }
}

/**
 * createAudioManager(options)
 *   app          'participant' | 'admin' | 'public' | 'stage' (localStorage key + preload list)
 *   baseUrl      directory of the WAV files            (default /assets/audio)
 *   manifestUrl  audio.json for loop points/checksums  (default /assets/manifest/audio.json; optional)
 *   manifest     an already-loaded manifest object     (skips the fetch)
 *   clockNow     () => server-time ms, used to convert play(id, { at }) for the Float sync
 *   translate    (copyKey, vars) => string, e.g. `t` from packages/contracts; captions fall back to plain text
 *   onCaption    ({ id, caption, played, reason, delayMs }) => void   (also addable with onCaption(fn))
 *   startMuted   initial mute when no stored preference exists (default false)
 *   volume       initial master volume when no stored preference exists (default 1)
 *   maxVoices    concurrent one-shot voices (default 4)
 *   lateToleranceMs  a scheduled cue older than this is dropped as stale (default 400)
 *   storage / fetch / audioContextClass   injection points for tests
 */
export function createAudioManager(options = {}) {
  const opts = Object.assign({
    app: 'app', baseUrl: DEFAULT_BASE_URL, manifestUrl: DEFAULT_MANIFEST_URL, manifest: null,
    clockNow: null, translate: null, onCaption: null, startMuted: false, volume: 1,
    maxVoices: MAX_VOICES, lateToleranceMs: 400, storage: undefined, fetch: undefined, audioContextClass: undefined,
  }, options || {});

  const AC = opts.audioContextClass || globalThis.AudioContext || globalThis.webkitAudioContext || null;
  const supported = typeof AC === 'function';
  const fetchFn = opts.fetch || (typeof globalThis.fetch === 'function' ? globalThis.fetch.bind(globalThis) : null);
  const storageKey = STORAGE_PREFIX + String(opts.app || 'app');

  const st = {
    ctx: null, master: null, ambientGain: null, cueBus: null,
    unlocked: false, autoplayDenied: false, muted: !!opts.startMuted, volume: clamp01(opts.volume),
    available: {}, buffers: new Map(), manifest: opts.manifest || null, manifestLoaded: !!opts.manifest,
    lastPlayed: new Map(), voices: [], ambient: null, ambientPlaying: false,
    replaying: false, epoch: -Infinity, duckUntil: 0, disposed: false,
    captionListeners: [], preloading: new Map(), lastError: null,
  };
  for (const id of Object.keys(CUES)) st.available[id] = 'pending';
  if (typeof opts.onCaption === 'function') st.captionListeners.push(opts.onCaption);

  // ---- persistence (per app) -------------------------------------------------------------
  function storage() {
    if (opts.storage !== undefined) return opts.storage;
    try { return globalThis.localStorage || null; } catch (_) { return null; }
  }
  function loadPrefs() {
    try {
      const s = storage(); if (!s) return;
      const raw = s.getItem(storageKey); if (!raw) return;
      const p = JSON.parse(raw);
      if (typeof p.muted === 'boolean') st.muted = p.muted;
      if (p.volume != null) st.volume = clamp01(p.volume);
    } catch (_) { /* ignore */ }
  }
  function savePrefs() {
    try { const s = storage(); if (s) s.setItem(storageKey, JSON.stringify({ muted: st.muted, volume: st.volume })); } catch (_) { /* ignore */ }
  }
  loadPrefs();

  // ---- captions ----------------------------------------------------------------------------
  function captionText(id, vars) {
    const cue = CUES[id]; if (!cue) return '';
    if (cue.copyKey && typeof opts.translate === 'function') {
      try { const t = opts.translate(cue.copyKey, vars || {}); if (typeof t === 'string' && t && t !== cue.copyKey) return t; } catch (_) { /* fall through */ }
    }
    return cue.caption;
  }
  function emitCaption(payload) {
    for (const fn of st.captionListeners.slice()) { try { fn(payload); } catch (_) { /* listener errors never propagate */ } }
  }

  // ---- graph -------------------------------------------------------------------------------
  function ensureContext() {
    if (st.ctx || !supported || st.disposed) return st.ctx;
    try {
      st.ctx = new AC();
      st.master = st.ctx.createGain();
      st.master.gain.value = st.muted ? 0 : st.volume;
      st.master.connect(st.ctx.destination);
      st.cueBus = st.ctx.createGain(); st.cueBus.gain.value = 1; st.cueBus.connect(st.master);
      st.ambientGain = st.ctx.createGain(); st.ambientGain.gain.value = 0; st.ambientGain.connect(st.master);
    } catch (e) { st.ctx = null; st.lastError = 'context'; }
    return st.ctx;
  }
  function applyMaster() {
    if (!st.master || !st.ctx) return;
    try {
      const g = st.master.gain, t = st.ctx.currentTime;
      const target = st.muted ? 0 : st.volume;
      if (typeof g.cancelScheduledValues === 'function') g.cancelScheduledValues(t);
      if (typeof g.setValueAtTime === 'function' && typeof g.linearRampToValueAtTime === 'function') {
        g.setValueAtTime(g.value, t); g.linearRampToValueAtTime(target, t + 0.05);
      } else g.value = target;
    } catch (_) { /* ignore */ }
  }
  function decode(ctx, ab) {
    return new Promise((resolve, reject) => {
      try {
        const p = ctx.decodeAudioData(ab, resolve, reject);
        if (p && typeof p.then === 'function') p.then(resolve, reject);
      } catch (e) { reject(e); }
    });
  }

  async function loadManifest() {
    if (st.manifestLoaded || !fetchFn || !opts.manifestUrl) return st.manifest;
    st.manifestLoaded = true;
    try {
      const r = await fetchFn(opts.manifestUrl);
      if (r && r.ok) st.manifest = await r.json();
    } catch (_) { st.manifest = null; }
    return st.manifest;
  }
  function manifestEntry(id) {
    const m = st.manifest; if (!m || !Array.isArray(m.cues)) return null;
    return m.cues.find((c) => c && c.id === id) || null;
  }

  // ---- public API --------------------------------------------------------------------------
  async function unlock() {
    try {
      if (st.disposed || !supported) return false;
      const ctx = ensureContext(); if (!ctx) return false;
      if (ctx.state === 'suspended' && typeof ctx.resume === 'function') {
        try { await ctx.resume(); } catch (_) { /* fall through to the state check */ }
      }
      if (ctx.state !== 'running') { st.autoplayDenied = true; return false; }
      st.unlocked = true; st.autoplayDenied = false; applyMaster();
      return true;
    } catch (e) { st.autoplayDenied = true; return false; }
  }

  async function preload(ids) {
    try {
      const list = Array.isArray(ids) && ids.length ? ids : (PRELOAD_BY_APP[opts.app] || Object.keys(CUES));
      if (!supported || st.disposed) { for (const id of list) if (CUES[id]) st.available[id] = 'unavailable'; return { ...st.available }; }
      const ctx = ensureContext(); if (!ctx) { for (const id of list) if (CUES[id]) st.available[id] = 'unavailable'; return { ...st.available }; }
      await loadManifest();
      await Promise.allSettled(list.map((id) => preloadOne(id)));
      return { ...st.available };
    } catch (_) { return { ...st.available }; }
  }
  function preloadOne(id) {
    const cue = CUES[id]; if (!cue) return Promise.resolve(false);
    if (st.buffers.has(id)) return Promise.resolve(true);
    if (st.preloading.has(id)) return st.preloading.get(id);
    const p = (async () => {
      try {
        if (!fetchFn || !st.ctx) throw new Error('no fetch/context');
        const base = String(opts.baseUrl || '').replace(/\/$/, '');
        const r = await fetchFn(`${base}/${cue.file}`);
        if (!r || !r.ok) throw new Error('http');
        const ab = await r.arrayBuffer();
        const buf = await decode(st.ctx, ab);
        if (!buf) throw new Error('decode');
        st.buffers.set(id, buf); st.available[id] = 'ready';
        return true;
      } catch (_) { st.available[id] = 'unavailable'; return false; }
      finally { st.preloading.delete(id); }
    })();
    st.preloading.set(id, p);
    return p;
  }

  function pruneVoices() {
    const t = st.ctx ? st.ctx.currentTime : 0;
    st.voices = st.voices.filter((v) => !v.ended && v.endsAt > t);
  }
  function stopVoice(v) { try { v.ended = true; v.source.stop(); } catch (_) { /* ignore */ } }

  function play(id, playOpts = {}) {
    try {
      const cue = CUES[id]; if (!cue || cue.loop || st.disposed) return false;
      const o = playOpts || {};
      // Replay guards: never re-celebrate old events after a reconnect.
      if (st.replaying || o.fresh === false) return false;
      if (o.sequence != null && Number(o.sequence) <= st.epoch) return false;
      // Schedule against server time when requested (Float sync).
      let delayMs = 0;
      const atMs = toMs(o.at);
      if (atMs != null) {
        const serverNow = typeof opts.clockNow === 'function' ? Number(opts.clockNow()) : Date.now();
        delayMs = atMs - (Number.isFinite(serverNow) ? serverNow : Date.now());
        if (delayMs < -Number(opts.lateToleranceMs || 0)) return false; // stale
        if (delayMs < 0) delayMs = 0;
      }
      // Per-cue rate limit.
      const now = nowMs();
      const last = st.lastPlayed.get(id);
      if (cue.rateLimitMs > 0 && last != null && now + delayMs - last < cue.rateLimitMs) return false;

      const caption = captionText(id, o.vars);
      let played = false, reason = 'ok';
      if (!supported) reason = 'unsupported';
      else if (!st.unlocked) reason = st.autoplayDenied ? 'autoplay-denied' : 'locked';
      else if (st.muted) reason = 'muted';
      else if (!st.buffers.has(id)) { reason = st.available[id] === 'unavailable' ? 'unavailable' : 'not-loaded'; if (reason === 'not-loaded') preloadOne(id); }
      else played = startVoice(id, cue, delayMs, o);
      if (!played && reason === 'ok') reason = 'voice-limit';
      if (played) st.lastPlayed.set(id, now + delayMs); // the rate limit counts audible plays only
      const payload = { id, caption, played, reason, delayMs };
      if (delayMs > 0) later(() => emitCaption(payload), delayMs); else emitCaption(payload);
      return played;
    } catch (e) { st.lastError = 'play'; return false; }
  }

  function startVoice(id, cue, delayMs, o) {
    try {
      const ctx = st.ctx; const buf = st.buffers.get(id);
      pruneVoices();
      if (st.voices.length >= Number(opts.maxVoices || MAX_VOICES)) {
        let lowest = st.voices[0];
        for (const v of st.voices) if (v.priority < lowest.priority || (v.priority === lowest.priority && v.endsAt < lowest.endsAt)) lowest = v;
        if (lowest.priority > cue.priority) return false; // higher-priority voices keep playing; drop the newcomer
        stopVoice(lowest); pruneVoices();
      }
      const when = ctx.currentTime + delayMs / 1000;
      const src = ctx.createBufferSource(); src.buffer = buf;
      const g = ctx.createGain(); g.gain.value = dbToLin(o.gainDb || 0);
      src.connect(g); g.connect(st.cueBus);
      const voice = { id, priority: cue.priority, source: src, endsAt: when + (buf.duration || 0), ended: false };
      src.onended = () => { voice.ended = true; try { src.disconnect(); g.disconnect(); } catch (_) { /* ignore */ } pruneVoices(); };
      src.start(when);
      st.voices.push(voice);
      if (cue.duck) duck(cue.duck.db, cue.duck.ms, delayMs);
      return true;
    } catch (e) { st.lastError = 'voice'; return false; }
  }

  function startAmbient() {
    try {
      if (st.disposed || !supported || !st.unlocked || !st.ctx) return false;
      if (st.ambientPlaying) return true;
      const buf = st.buffers.get('ambient_galaxy'); if (!buf) { preloadOne('ambient_galaxy'); return false; }
      const ctx = st.ctx;
      const src = ctx.createBufferSource(); src.buffer = buf; src.loop = true;
      const entry = manifestEntry('ambient_galaxy');
      const sr = (entry && entry.sample_rate) || buf.sampleRate || 22050;
      if (entry && entry.loop) { src.loopStart = entry.loop.start_sample / sr; src.loopEnd = entry.loop.end_sample / sr; }
      else { src.loopStart = 0; src.loopEnd = buf.duration || 0; }
      src.connect(st.ambientGain);
      const g = st.ambientGain.gain, t = ctx.currentTime;
      if (typeof g.cancelScheduledValues === 'function') g.cancelScheduledValues(t);
      if (typeof g.setValueAtTime === 'function') { g.setValueAtTime(0, t); g.linearRampToValueAtTime(1, t + AMBIENT_FADE_IN_S); } else g.value = 1;
      src.start(t);
      st.ambient = src; st.ambientPlaying = true;
      src.onended = () => { if (st.ambient === src) { st.ambient = null; st.ambientPlaying = false; } };
      emitCaption({ id: 'ambient_galaxy', caption: captionText('ambient_galaxy'), played: true, reason: 'ok', delayMs: 0 });
      return true;
    } catch (e) { st.lastError = 'ambient'; return false; }
  }

  function stopAmbient() {
    try {
      if (!st.ambient || !st.ctx) { st.ambientPlaying = false; return true; }
      const src = st.ambient, g = st.ambientGain.gain, t = st.ctx.currentTime;
      if (typeof g.cancelScheduledValues === 'function') g.cancelScheduledValues(t);
      if (typeof g.setValueAtTime === 'function') { g.setValueAtTime(g.value, t); g.linearRampToValueAtTime(0, t + AMBIENT_FADE_OUT_S); src.stop(t + AMBIENT_FADE_OUT_S + 0.05); }
      else { g.value = 0; src.stop(); }
      st.ambient = null; st.ambientPlaying = false;
      return true;
    } catch (e) { st.ambientPlaying = false; return false; }
  }

  function duck(db, ms, delayMs = 0) {
    try {
      if (!st.ctx || !st.ambientGain) return false;
      const depth = Math.min(1, Math.max(0, dbToLin(-Math.abs(Number(db) || 0))));
      const hold = Math.max(0, Number(ms) || 0) / 1000;
      const g = st.ambientGain.gain, t0 = st.ctx.currentTime + Math.max(0, Number(delayMs) || 0) / 1000;
      const end = t0 + 0.03 + hold + 0.4;
      if (end < st.duckUntil) return true; // an equal-or-longer duck is already scheduled
      if (typeof g.cancelScheduledValues !== 'function') return false;
      g.cancelScheduledValues(t0);
      g.setValueAtTime(st.ambientPlaying ? Math.max(g.value, 0) : 0, t0);
      g.linearRampToValueAtTime(st.ambientPlaying ? depth : 0, t0 + 0.03);
      g.setValueAtTime(st.ambientPlaying ? depth : 0, t0 + 0.03 + hold);
      g.linearRampToValueAtTime(st.ambientPlaying ? 1 : 0, end);
      st.duckUntil = end;
      return true;
    } catch (e) { return false; }
  }

  function setMuted(flag) { try { st.muted = !!flag; applyMaster(); savePrefs(); return st.muted; } catch (_) { return st.muted; } }
  function setMasterVolume(v) { try { st.volume = clamp01(v); applyMaster(); savePrefs(); return st.volume; } catch (_) { return st.volume; } }
  function setReplaying(flag) { st.replaying = !!flag; return st.replaying; }
  function setConnectionEpoch(sequence) { const n = Number(sequence); st.epoch = Number.isFinite(n) ? n : -Infinity; return st.epoch; }
  function onCaption(fn) {
    if (typeof fn !== 'function') return () => {};
    st.captionListeners.push(fn);
    return () => { st.captionListeners = st.captionListeners.filter((f) => f !== fn); };
  }
  function state() {
    try { pruneVoices(); } catch (_) { /* ignore */ }
    return {
      supported, unlocked: st.unlocked, muted: st.muted, volume: st.volume, autoplayDenied: st.autoplayDenied,
      available: { ...st.available }, ambientPlaying: st.ambientPlaying, replaying: st.replaying,
      activeVoices: st.voices.filter((v) => !v.ended).length, epoch: st.epoch, lastError: st.lastError,
    };
  }
  function dispose() {
    try {
      st.disposed = true;
      for (const v of st.voices) stopVoice(v);
      st.voices = [];
      stopAmbient();
      if (st.ctx && typeof st.ctx.close === 'function') st.ctx.close().catch(() => {});
    } catch (_) { /* ignore */ }
    st.ctx = null; st.unlocked = false;
  }

  return Object.freeze({
    unlock, preload, play, startAmbient, stopAmbient, duck, setMuted, setMasterVolume,
    setReplaying, setConnectionEpoch, onCaption, caption: captionText, state, dispose,
    cues: CUES, app: String(opts.app || 'app'),
  });
}

export default createAudioManager;
