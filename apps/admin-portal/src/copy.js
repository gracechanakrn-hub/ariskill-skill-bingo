/** t(key, vars): catalog first; `adminLocal.*` proposals second; the key itself last (visible, never silent). */
export function t(key, vars = {}) {
  const fromCatalog = catalogT(key, vars);
  if (fromCatalog !== key) return fromCatalog;
  const local = PROPOSED_ADMIN_COPY[key];
  if (local === undefined) return key;
  return local.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}

export function exception(id) { return catalogException(id); }
export function exceptionCopy(id, fallback = '') { const e = catalogException(id); return e ? e.copy : fallback; }
